import { formatDate } from '~/utils/helpers'

export function useFormat() {
  const formatCurrency = (amount: number) => {
    return new Intl.NumberFormat('id-ID', {
      style: 'currency',
      currency: 'IDR',
      minimumFractionDigits: 0,
    }).format(amount)
  }

  return { formatDate, formatCurrency }
}
